// pdf/cos/filters/Jbig2Filter -- `/JBIG2Decode`. ISO 32000-1 7.4.7, ITU-T T.88. Stage 2 T7.
//
// ============================================================================================
// THIS FILTER IS DECLARED AND REFUSES BY NAME. READ WHY BEFORE "FINISHING" IT.
// ============================================================================================
//
// It is the ninth of the nine filters D2-4 lists, it exists so the chain in `Filter.cpp` is
// complete and so `/JBIG2Decode` produces a NAMED `Unsupported` rather than an unknown-filter
// error or -- far worse -- an empty buffer that a caller mistakes for a blank page. What it does
// not do is decode. That is a deviation from T7's task row, and it is recorded as issue **I-06**
// in `Stage2-Rendering-Testing-Guide.md` §8 rather than absorbed quietly, per
// `Stage2-Rendering-Plan.md` §12's rule about overrun.
//
// THREE FACTS FORCED IT, and all three were established rather than assumed:
//
//   1. **There is no permissible library.** The one usable open-source JBIG2 decoder is
//      Ghostscript's `jbig2dec`, which is **AGPL-3.0**. `Tech-Stack-Plan.md` D4 forbids any GPL or
//      AGPL dependency outright and `license-audit` enforces it mechanically, so linking it is not
//      a trade-off to weigh -- it is a build failure. PDFium has its own decoder, but PDFium is
//      behind the `FPDF_` boundary that `layer-lint` forbids `pdf/cos/` from crossing (D2-9), and
//      that boundary is half of D3: we read through PDFium and write through our own code.
//   2. **There is no corpus fixture.** `corpus/` has DCT, JPX, CCITT G3, CCITT G4, Flate,
//      LZW and RunLength images and **no JBIG2 file at all** -- checked against
//      `corpus/PROVENANCE.md`, not remembered. D2-11 says in as many words that *a construct the
//      corpus never contains is a construct nothing in this project ever renders*, so a decoder
//      written here would be the only unfixtured codec in the tree.
//   3. **Nothing in Stage 2 would call it.** Rendering goes through PDFium, which decodes JBIG2
//      itself. The first real consumer is Stage 8's image export.
//
// Together those are exactly the argument **D2-4** already accepted for `CryptFilter`: *"building
// it here produces a file that cannot be tested and will be rewritten"*. The difference is that
// CryptFilter's deferral is a recorded decision and this one is a finding, which is why it is
// written up rather than merely done.
//
// WHAT FINISHING IT COSTS, so the estimate is on the record rather than rediscovered: an MQ
// arithmetic decoder, segment-header parsing, and generic region decoding for templates 0-3 with
// TPGDON -- call it 450 lines -- **plus** a first-party `corpus/jbig2enc.py` to produce the
// fixture, since every corpus file is generated by us (D2-11). Symbol dictionaries and text
// regions, which some encoders emit, are more again. The honest sequencing is corpus first,
// decoder second, because the decoder cannot be believed without the fixture.

#ifndef RAWPAGE_PDF_COS_FILTERS_JBIG2FILTER_H
#define RAWPAGE_PDF_COS_FILTERS_JBIG2FILTER_H

#include "pdf/cos/filters/Filter.h"

namespace rawpage::pdf::cos::filters {

// `globals` is the `/JBIG2Globals` stream's decoded bytes when the image dictionary names one --
// the parameter exists now so the signature does not change when the decoder lands, because a
// signature change is what makes a deferral expensive later.
//
// ALWAYS returns `Unsupported` with `error.pdf.filterJbig2`, which is a DIFFERENT key from the
// generic unsupported-filter one: a reader seeing this in a log should learn "this build cannot
// read JBIG2", not "this file names a filter nobody has heard of".
core::Result<Bytes> jbig2Decode(std::string_view input, std::string_view globals);

} // namespace rawpage::pdf::cos::filters

#endif // RAWPAGE_PDF_COS_FILTERS_JBIG2FILTER_H

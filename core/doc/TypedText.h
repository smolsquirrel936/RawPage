// core/doc/TypedText -- the text a person TYPES into a comment, as an appearance will draw it: which face
// draws each character, which characters none can, where the lines break, and the free-text box that holds
// them. Stage 6 T7, decisions D6-7, D6-8 and D6-34 (`Stage6-Annotations-Plan.md` §3).
//
// ===========================================================================================
// FIVE FACES, NONE EMBEDDED (D6-7)
// ===========================================================================================
// Base-14 Helvetica in WinAnsiEncoding for every character Windows code page 1252 holds, and the four
// predefined Adobe CJK collections -- through their UCS-2 CMaps, so the code written IS the character --
// for Chinese, Japanese and Korean. No font is embedded: embedding needs subsetting, which is Stage 8's and
// Stage 13's. A reader draws Helvetica from its own copy and a CJK collection with the machine's CJK face
// (Stage 5 T1 measured PDFium drawing `STSong-Light` as SimSun).
//
// ===========================================================================================
// A CHARACTER NONE OF THEM CAN SHOW IS REFUSED, BY NAME (D6-7, guide case A-56)
// ===========================================================================================
// A character outside WinAnsi and outside every collection's coverage -- Greek, Cyrillic, Hebrew, Arabic,
// Thai, an ideograph no collection holds, anything past the Basic Multilingual Plane (a UCS-2 CMap has no
// code for it) -- is refused, and the refusal names it. Drawing it would be a box, or nothing: *text that
// is not there* was Stage 5's S1. **Which characters each collection holds is a TABLE** (`CjkCoverage.inc`,
// generated by `tools/cjk-coverage/make-cjk-coverage.py` from each collection's legacy character set), and
// that table is a claim the engine is held to: `tests/render/tst_typedtext.cpp` writes every character it
// lists and requires PDFium to read each one back and draw it. Only CJK characters and the symbols CJK
// text uses are in it -- GB 2312 holds Greek, and D6-7 refuses Greek (`DW-3`).
//
// ===========================================================================================
// WHICH COLLECTION DRAWS A CHARACTER (D6-34)
// ===========================================================================================
// Kana is Japanese and Hangul is Korean, whatever surrounds them; an ideograph is all four, and which
// country's forms it is drawn in is a LANGUAGE, which the characters alone do not say. So each run of CJK
// characters (between two Latin ones) is drawn in Japanese when it holds kana, in Korean when it holds
// Hangul, and otherwise in the HAN PREFERENCE -- the CJK font the annotation's `/DA` already names, else the
// person's input language, which the HOST supplies (convention 11: the rule is here, the language is the
// host's). The first CJK run decides the annotation's PRIMARY font, which `/DA` names -- so an annotation
// redrawn later from its own `/DA` draws every character in the same face as before. A character the chosen
// collection lacks is drawn by the first of Simplified, Traditional, Japanese and Korean that holds it.
//
// ===========================================================================================
// LINES, AND THE BOX AROUND THEM
// ===========================================================================================
// A paragraph breaks at a space after a word and between any two CJK characters; a word longer than the
// line breaks between letters. A soft break keeps its space at the end of the line it ends -- drawn, and
// invisible -- so the characters an appearance shows are exactly the characters typed, line breaks aside
// (guide case A-57). A line is `kTypedLeading` ems tall and its baseline `kTypedAscent` ems below its top:
// a block of n lines is exactly n × 1.2 ems, which is what a box is fitted to.
//
// Pure: QtCore and std only -- `tst_typedtext` in `rawpage_tests`; against the ENGINE, `render.`'s.


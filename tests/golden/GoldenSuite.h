// tests/golden/GoldenSuite -- the golden-image engine, shared by the suite and by the tool.
// Stage 2 T17. Decisions D2-3 and D2-13 (`claude-plan/Stage2-Rendering-Plan.md` §3).
//
// ===============================================================================================
// WHY ONE FILE SERVES BOTH, AND WHY IT LIVES HERE RATHER THAN IN tools/
// ===============================================================================================
//
// `tests/golden` compares renders against committed baselines; `tools/golden-update` produces
// those baselines. If the two used different code to render, to encode, or to decide what "the
// same" means, the tool would write files the suite could not accept -- and the failure would look
// like a rendering regression rather than like a disagreement between two programs. That is the
// exact failure `tools/ribbon-validate/CMakeLists.txt` records for the ribbon schema: *a validator
// that certifies a file the runtime then reads differently*. So there is one renderer, one PNG
// codec and one comparison, compiled into both binaries.
//
// It lives in `tests/` because that is the direction `Architecture-FileMap.md` §3.17 already
// declares: `tools/golden-update/` lists `golden/` and `tests/golden/` among its dependencies, and
// nothing lists `tools/` as a dependency of the suite. `tools/golden-update` COMPILES this file in
// rather than linking it, which is the same technique `ribbon-validate` uses for `RibbonModel.cpp`
// and `tests/unit` for `app/CommandLine.cpp`.
//
// ===============================================================================================
// WHAT A GREEN GOLDEN RUN CLAIMS, AND WHAT IT DOES NOT
// ===============================================================================================
//
// It claims: **the product rasterizes our own corpus the same way it did when the baselines were
// captured, on this rasterizer, at these three resolutions.** It does NOT claim the output is
// correct -- a baseline captured from a wrong renderer is green forever, which is why manual case
// M-03 puts a person beside Acrobat. And it does not claim anything about real-world PDFs: every
// corpus file is generated by us (D2-11), and a generator emits only what its author already
// understood.
//
// ===============================================================================================
// THE THREE THINGS THAT MAKE A BASELINE REPRODUCIBLE, ALL OF WHICH ARE EASY TO GET WRONG
// ===============================================================================================
//
//  1. **`RenderFlags::NoNativeText`.** `core/render/RenderRequest.h` has carried that flag since T9
//     with the comment *"required for reproducible goldens"*, and this is the file that cashes it.
//     Without it PDFium may hand text to the OS renderer, whose output depends on the machine's
//     ClearType and gamma settings -- a baseline that is a claim about a control panel.
//
//  2. **The base-14 fonts must come from PDFium's own copies.** They do, because
//     `pdf/render/FontResolverBridge` declines them by name (issue **I-13**, found at T16 by a
//     control case one task before these baselines were captured). Had it not, every baseline here
//     would have been a claim about whichever Segoe UI shipped with this Windows build.
//
//  3. **A substituted face is NOT reproducible, and the manifest says which cases are affected.**
//     `corpus/ordinary/font-not-embedded.pdf` names two families that exist on no machine, so what
//     is drawn is whatever `core/render/FontSubstitution`'s candidate list found installed HERE.
//     Such a case is marked `machineDependent` in `golden/manifest.json`, its capture-time
//     substitutions are recorded in `golden/captured.json`, and the suite **skips it by name** on a
//     machine that resolves differently rather than reporting a rendering regression. That is guide
//     case A-62's rule -- report not applicable explicitly rather than pass vacuously -- applied to
//     a second subject.

#ifndef RAWPAGE_TESTS_GOLDEN_GOLDENSUITE_H
#define RAWPAGE_TESTS_GOLDEN_GOLDENSUITE_H

#include "core/backend.h"
#include "core/render/RenderRequest.h"
#include "pdf/render/FontResolverBridge.h"

#include <QString>
#include <QStringList>

#include <memory>
#include <vector>

namespace rawpage::golden {

// -----------------------------------------------------------------------------------------
// The comparison thresholds -- DATA, because D2-13 requires the threshold to be *stated*
// -----------------------------------------------------------------------------------------
// Two thresholds rather than one, and the pair is the whole of "perceptual with a stated
// threshold". Antialiasing drift is MANY pixels each off by a LITTLE; a real regression -- a
// shifted glyph, a missing hairline, a wrong colour -- is either many pixels or a few pixels off by
// a LOT. One threshold cannot separate those: set loose enough to absorb the first it accepts the
// second, and set tight enough to catch the second it fails on a rasterizer rebuild.
struct Thresholds {
    int    channelTolerance      = 8;       // a pixel "differs" above this per-channel delta
    double differingFraction     = 0.0010;  // ...and at most this fraction of the page may
    int    grossChannelTolerance = 96;      // a pixel is "grossly" wrong above this delta
    double grossFraction         = 0.0001;  // ...and almost none may be
};

// One declared baseline family: a corpus file, the pages of it that are captured, and at which
// resolutions. Hand-authored in `golden/manifest.json` and reviewed like code.
struct Case {
    QString          file;              // corpus-relative, e.g. "ordinary/text-a4.pdf"
    std::vector<int> pages;
    std::vector<int> dpi;
    QString          password;          // empty means the file is not encrypted
    bool             machineDependent = false;
    QString          note;
};

struct Exclusion {
    QString file;
    QString reason;
};

struct Manifest {
    int                    formatVersion = 0;
    Thresholds             thresholds;
    std::vector<int>       defaultDpi;
    std::vector<Case>      cases;
    std::vector<Exclusion> excluded;

    // Non-empty means the manifest could not be read. A manifest that fails to parse must not
    // yield an empty-but-valid case list: zero baselines compared is a passing run.
    QString error;

    int imageCount() const;
    const Case* find(const QString& file) const;
};

Manifest loadManifest(const QString& path);

// `golden/`-relative location of one baseline: "ordinary/text-a4/144/p000.png". The DPI is zero
// padded so a directory listing sorts the way a person reads it.
QString baselineRelativePath(const Case& item, int page, int dpi);

// -----------------------------------------------------------------------------------------
// Rendering one baseline
// -----------------------------------------------------------------------------------------
// The engine session installs the font bridge over a real `WinFontResolver` -- the arrangement the
// shipped product runs, not a convenient subset of it -- and takes it out again on destruction,
// because a hook left pointing at a destroyed resolver is a use-after-free inside PDFium in a stack
// frame nobody recognizes (`pdf/render/FontResolverBridge.h`, and `app/CompositionRoot`'s teardown
// order for the same reason).
class EngineSession {
public:
    EngineSession();
    ~EngineSession();

    EngineSession(const EngineSession&) = delete;
    EngineSession& operator=(const EngineSession&) = delete;

    bool           isReady() const;
    const QString& error() const;

private:
    struct Impl;
    std::unique_ptr<Impl> impl_;
};

struct RenderOutcome {
    bool              ok = false;
    QString           error;
    core::RasterImage image;

    // Every font PDFium asked us to map while this page was drawn. Recorded at capture time for a
    // `machineDependent` case and compared at test time; see the header note.
    std::vector<pdf::render::FontResolverBridge::Substitution> substitutions;
};

// Renders ONE WHOLE PAGE in one call, through the product's own arithmetic:
// `core::render::Resolution` at the requested DPI, `TileGrid::pageBounds` for the pixel rect,
// `PdfiumRasterizer` for the pixels.
//
// WHOLE PAGE RATHER THAN COMPOSED TILES, deliberately. The two must agree -- that is guide case
// A-44's claim and `tst_golden.cpp` re-asserts it against a committed baseline rather than against
// itself -- but a baseline built by composing tiles would fold the composition step's own bugs into
// the reference, and a reference cannot be wrong in a way its own producer shares.
//
// `extraFlags` exists for exactly one caller: the negative control that perturbs a render to prove
// the comparison can fail (guide case A-49). Nothing else passes it.
RenderOutcome renderPage(const QString& corpusRoot, const Case& item, int page, int dpi,
                         core::render::RenderFlags extraFlags = core::render::RenderFlags::None);

// How many pages the engine reports for a case, or -1 if it will not open. Used by `--survey` when
// a manifest is being authored: which pages to capture is the one decision that cannot be made
// without opening the file.
int pageCount(const QString& corpusRoot, const Case& item);

// The same page, composed from the tiles `TileGrid` would ask for. Used by the one case that
// asserts the tiled path and the whole-page path produce the same pixels.
RenderOutcome renderPageFromTiles(const QString& corpusRoot, const Case& item, int page, int dpi);

// -----------------------------------------------------------------------------------------
// PNG, through QtGui
// -----------------------------------------------------------------------------------------
// QImage rather than a first-party encoder, for two reasons and against one objection.
//
// The reasons: Qt's PNG handler is built into QtGui rather than being a plugin, so it works in a
// process with no display and no `QGuiApplication`; and QtGui is already in this project's Qt link
// closure through `rawpage_ui`, so `tools/license-audit` sees nothing new.
//
// The objection is that the ENCODER is not pinned, so a Qt upgrade could re-encode identical pixels
// into different bytes and show as a diff in `git`. That is accepted: **the comparison is over
// decoded pixels, never over file bytes**, so an encoder change cannot turn a green suite red. It
// is `corpus/`'s byte-identical rule deliberately NOT applied here -- a corpus file's bytes are the
// fixture, a baseline's pixels are.
bool writePng(const QString& path, const core::RasterImage& image, QString* error);
bool readPng(const QString& path, core::RasterImage* out, QString* error);

// -----------------------------------------------------------------------------------------
// Comparison
// -----------------------------------------------------------------------------------------
struct Comparison {
    bool      sizeMatches      = false;
    int       expectedWidth    = 0;
    int       expectedHeight   = 0;
    int       actualWidth      = 0;
    int       actualHeight     = 0;
    long long totalPixels      = 0;
    long long differingPixels  = 0;
    long long grossPixels      = 0;
    int       maxChannelDelta  = 0;
    int       firstDifferentX  = -1;
    int       firstDifferentY  = -1;

    bool    passes(const Thresholds& thresholds) const;
    double  differingRatio() const;
    double  grossRatio() const;

    // A sentence a person can act on. "golden mismatch, 0.7 % of pixels" is not a bug report
    // (D2-13); this names the worst pixel, where it is, and which half of the threshold was
    // exceeded.
    QString describe(const Thresholds& thresholds) const;
};

Comparison compare(const core::RasterImage& expected, const core::RasterImage& actual,
                   const Thresholds& thresholds);

// Writes `<stem>-expected.png`, `<stem>-actual.png` and `<stem>-diff.png`. The diff paints matching
// pixels as a faint ghost of the actual and differing ones in red scaled by their delta, so the
// answer to *where* is the first thing a reader sees. Returns the directory it wrote into.
bool writeFailureImages(const QString& stem, const core::RasterImage& expected,
                        const core::RasterImage& actual, const Thresholds& thresholds,
                        QString* error);

// -----------------------------------------------------------------------------------------
// Capture metadata -- the MEASURED half, written by the tool and read by the suite
// -----------------------------------------------------------------------------------------
// `golden/manifest.json` is the DECLARATION and is hand-authored; this is what was actually true
// when the baselines were made. The split is `cmake/PdfiumAssert.cmake`'s: expected values live in
// the file a person edits, found values live where the machine put them, and the asymmetry is the
// check.
struct CaptureRecord {
    QString     file;
    int         page = 0;
    int         dpi = 0;
    int         width = 0;
    int         height = 0;
    QStringList substitutions;   // "requested -> chosen [outcome]", capture-time
};

struct CaptureLog {
    QString                    pdfiumVersion;
    QString                    capturedUtc;
    QString                    reason;
    std::vector<CaptureRecord> records;
    QString                    error;

    const CaptureRecord* find(const QString& file, int page, int dpi) const;
};

CaptureLog loadCaptureLog(const QString& path);
bool       writeCaptureLog(const QString& path, const CaptureLog& log, QString* error);

// The substitution rows a render performed, in the form `CaptureRecord::substitutions` stores.
// One function so the tool's writing and the suite's reading cannot spell it differently.
QStringList describeSubstitutions(
    const std::vector<pdf::render::FontResolverBridge::Substitution>& rows);

// Every `.pdf` under `corpusRoot`, corpus-relative and sorted. Used by the manifest-coverage check
// so that a corpus file added later cannot silently have no baseline and no stated reason.
QStringList corpusFiles(const QString& corpusRoot);

} // namespace rawpage::golden

#endif // RAWPAGE_TESTS_GOLDEN_GOLDENSUITE_H

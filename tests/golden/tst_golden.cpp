// tst_golden -- guide cases A-48, A-49, A-50 and A-51's runtime half. Stage 2 T17.
//
// ===============================================================================================
// WHAT THIS SUITE CLAIMS, IN THE WORDS THE SIGN-OFF HAS TO USE
// ===============================================================================================
//
// **The product rasterizes our own corpus the same way it did when these baselines were captured.**
// Not that it rasterizes correctly -- a baseline captured from a wrong renderer is green forever,
// which is why manual case M-03 puts a person beside Acrobat -- and not anything at all about
// real-world PDFs, because every corpus file is generated by us (D2-11) and a generator emits only
// what its author already understood. `Stage2-Rendering-Testing-Guide.md` §1 states that bound and
// §13 requires the sign-off to repeat it rather than let *"every corpus file renders correctly"*
// stand.
//
// ===============================================================================================
// THE FOUR CONTROLS, AND WHY EACH ONE EXISTS
// ===============================================================================================
//
// Convention 7 says a control must fail for the right reason; convention 22 -- bought with T16's
// I-13 -- says a NEW mechanism needs controls written from *what must stay untouched* rather than
// from the criterion. This suite is a new mechanism, so:
//
//   1. **A perturbed render must fail** (A-49). Without it a comparison that returned "same" for
//      everything would pass every case in this file, and a golden suite that cannot fail is
//      decorative.
//   2. **An unperturbed render must pass.** The other half: a comparison that returned "different"
//      for everything would also make case 1 green.
//   3. **The tool must refuse without `--reason`** (A-50), driven as a child process, because the
//      refusal is the entire point of D2-3 and a refusal nothing exercises is a source comment.
//   4. **The recorded engine must be the running one** (A-51's runtime half). Configure already
//      refuses a version mismatch (`cmake/PdfiumAssert.cmake`), so reaching this check means the
//      DLL beside the executable was replaced after the build -- which is exactly the reader
//      `pdf/render/PdfiumInit.h`'s `version()` comment is written for.
//
// ===============================================================================================
// WHAT IT STILL DOES NOT COVER (convention 19)
// ===============================================================================================
//
// There is no widget and no screen here: this compares rasterizer output, and everything between a
// tile and a pixel on glass -- `TilePresenter`'s stride handling, the device-pixel-ratio conversion
// `ui/viewer/` owns, the monitor itself -- is `tests/ui`'s and the manual pass's. A page that is
// byte-perfect here and sheared on screen passes every assertion below.


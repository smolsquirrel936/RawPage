QString corpusRoot() { return QStringLiteral(RAWPAGE_CORPUS_DIR); }
QString goldenRoot() { return QStringLiteral(RAWPAGE_GOLDEN_DIR); }

QString baselinePath(const golden::Case& item, int page, int dpi)
{
    return QDir(goldenRoot()).filePath(golden::baselineRelativePath(item, page, dpi));
}

// Where a failing case leaves its three images. A fixed directory under the build tree rather than
// the working directory CTest happened to pick, so the failure message can print an absolute path
// that is still there afterwards.
QString failureStem(const golden::Case& item, int page, int dpi)
{
    QString stem = item.file;
    if (stem.endsWith(QLatin1String(".pdf"), Qt::CaseInsensitive)) stem.chop(4);
    stem.replace(QLatin1Char('/'), QLatin1Char('-'));
    return QDir(QStringLiteral(RAWPAGE_GOLDEN_FAILURE_DIR))
        .filePath(QStringLiteral("%1-%2dpi-p%3").arg(stem).arg(dpi).arg(page, 3, 10, QLatin1Char('0')));
}

const golden::Manifest& manifest()
{
    static const golden::Manifest loaded =
        golden::loadManifest(QDir(goldenRoot()).filePath(QStringLiteral("manifest.json")));
    return loaded;
}

const golden::CaptureLog& captureLog()
{
    static const golden::CaptureLog loaded =
        golden::loadCaptureLog(QDir(goldenRoot()).filePath(QStringLiteral("captured.json")));
    return loaded;
}

// A `machineDependent` case is compared only where this machine substitutes the SAME faces the
// capture did. Anywhere else the correct report is *not applicable*, by name -- guide case A-62's
// rule ("report not applicable explicitly rather than pass vacuously") applied to fonts instead of
// to a battery. Reporting it as a rendering regression is the failure this predicate exists to
// prevent, and it is the one CLAUDE.md's T17 note warns about by name.
bool substitutionsMatchCapture(const golden::Case& item, const golden::RenderOutcome& outcome,
                               const golden::CaptureRecord& record)
{
    if (!item.machineDependent) return true;
    return golden::describeSubstitutions(outcome.substitutions) == record.substitutions;
}

struct Skipped {
    int count = 0;
    QStringList reasons;
};

// One DPI's worth of the manifest, compared. Returns how many were skipped as not applicable, so
// the caller can assert that the whole run was not silently skipped -- "0 compared, 0 failed" is a
// passing run over nothing.
Skipped compareAtDpi(int dpi, int& compared)
{
    Skipped skipped;

    golden::EngineSession session;
    REQUIRE(session.isReady());

    for (const golden::Case& item : manifest().cases) {
        if (std::find(item.dpi.begin(), item.dpi.end(), dpi) == item.dpi.end()) continue;

        for (const int page : item.pages) {
            INFO("case " << item.file.toStdString() << " page " << page << " at " << dpi << " dpi");

            const QString expectedPath = baselinePath(item, page, dpi);
            REQUIRE(QFileInfo::exists(expectedPath));

            core::RasterImage expected;
            QString ioError;
            REQUIRE(golden::readPng(expectedPath, &expected, &ioError));

            const golden::RenderOutcome actual = golden::renderPage(corpusRoot(), item, page, dpi);
            INFO(actual.error.toStdString());
            REQUIRE(actual.ok);

            const golden::CaptureRecord* record = captureLog().find(item.file, page, dpi);
            REQUIRE(record != nullptr);

            if (!substitutionsMatchCapture(item, actual, *record)) {
                ++skipped.count;
                skipped.reasons
                    << QStringLiteral("%1 p%2 @%3: this machine substitutes [%4], the baseline "
                                      "records [%5]")
                           .arg(item.file).arg(page).arg(dpi)
                           .arg(golden::describeSubstitutions(actual.substitutions).join(
                               QLatin1String("; ")))
                           .arg(record->substitutions.join(QLatin1String("; ")));
                continue;
            }

            const golden::Comparison result =
                golden::compare(expected, actual.image, manifest().thresholds);
            if (!result.passes(manifest().thresholds)) {
                QString writeError;
                const QString stem = failureStem(item, page, dpi);
                golden::writeFailureImages(stem, expected, actual.image, manifest().thresholds,
                                           &writeError);
                FAIL_CHECK(item.file.toStdString()
                           << " page " << page << " at " << dpi << " dpi: "
                           << result.describe(manifest().thresholds).toStdString()
                           << "\n  expected / actual / diff written beside "
                           << stem.toStdString());
                continue;
            }
            ++compared;
        }
    }
    return skipped;
}

void reportSkips(const Skipped& skipped)
{
    for (const QString& reason : skipped.reasons)
        WARN("golden: not applicable -- " + reason.toStdString());
}

